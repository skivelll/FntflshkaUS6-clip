"""Generate reflected IEEE CRC32 operators for appending 2**k RGB565 pixels."""
from pathlib import Path


def apply(matrix, value):
    result = 0
    for bit, column in enumerate(matrix):
        if value & (1 << bit):
            result ^= column
    return result


def operators():
    # Linear shift-register transition for one zero bit, polynomial 0xEDB88320.
    matrix = [0xEDB88320] + [1 << bit for bit in range(31)]
    for _ in range(4):  # one RGB565 pixel =16 bits
        matrix = [apply(matrix,column) for column in matrix]
    result = []
    for _ in range(16):
        result.append(matrix)
        matrix = [apply(matrix,column) for column in matrix]
    return result


def source():
    lines = ['/* Generated by tools/generate_crc_operators.py; IEEE CRC32, no runtime RAM table. */',
             'static const uint32_t crc_pixel_shift[16][32] = {']
    for matrix in operators():
        lines.append('    {')
        for start in range(0,32,4):
            lines.append('        '+', '.join(f'0x{v:08X}U' for v in matrix[start:start+4])+',')
        lines.append('    },')
    return '\n'.join(lines+['};',''])


if __name__ == '__main__':
    (Path(__file__).resolve().parents[1]/'src/crc_pixel_shift.inc').write_text(source(),encoding='utf-8')
