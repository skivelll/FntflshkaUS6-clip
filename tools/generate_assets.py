"""Generate deterministic RGB565 test art without external dependencies."""

from pathlib import Path


def rgb565(red: int, green: int, blue: int) -> int:
    return ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)


def wide_pixel(x: int, y: int) -> int:
    if x < 2 or x >= 254 or y < 2 or y >= 126:
        return rgb565(235, 245, 255)
    if (x - 195) ** 2 + (y - 40) ** 2 <= 21 ** 2:
        return rgb565(255, 208, 64)
    if y >= 96 + (x - 128) // 12:
        return rgb565(14, 45, 86)
    if y >= 65 + abs(x - 72) // 4:
        return rgb565(40, 126, 137)
    return rgb565(18 + y // 5, 52 + y // 2, 116 + y // 3)


def heart_pixel(x: int, y: int) -> int:
    u = (x - 11.5) / 10.5
    v = (11.5 - y) / 10.5
    inside = (u * u + v * v - 1) ** 3 - u * u * v * v * v < 0
    if not inside:
        return rgb565(0, 0, 0)
    if 5 <= x <= 8 and 5 <= y <= 9:
        return rgb565(255, 180, 220)
    return rgb565(255, 54, 132)


def emit_array(name: str, width: int, height: int, pixel) -> str:
    values = [pixel(x, y) for y in range(height) for x in range(width)]
    lines = [f"static const uint16_t {name}[{width} * {height}] = {{"]
    for offset in range(0, len(values), 12):
        chunk = ", ".join(f"0x{value:04x}" for value in values[offset:offset + 12])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    output = Path(__file__).resolve().parents[1] / "src" / "generated_assets.inc"
    output.write_text(
        "// Generated by tools/generate_assets.py; do not edit by hand.\n"
        + emit_array("wide_pixels", 256, 128, wide_pixel)
        + "\n\n"
        + emit_array("heart_pixels", 24, 24, heart_pixel)
        + "\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
